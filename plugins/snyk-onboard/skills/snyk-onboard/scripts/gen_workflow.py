#!/usr/bin/env python3
"""Generate a GitHub Actions Snyk workflow tailored to a detected stack.

Usage:
  detect_stack.py --path . > stack.json
  gen_workflow.py stack.json [--severity high] [--org <snyk-org-slug>] [--repo-dir .] > .github/workflows/snyk.yml

Go repos get a short caller of the reusable pipeline in brightsheets/reusable-workflows
(go-ci.yaml: lint, tests, Snyk Open Source + Code, Docker build + Snyk Container when there is
a Dockerfile). --repo-dir lets it read go.mod to see whether private brightsheets modules are
needed. Other stacks, or --standalone, get a self-contained Snyk workflow.

  --org defaults to $SNYK_ORG, else "brightsheets" (https://app.snyk.io/org/brightsheets).
"""
import argparse, json, os, re

SETUP = {
    "javascript": "      - uses: actions/setup-node@v4\n        with: { node-version: 'lts/*' }\n      - run: npm ci --ignore-scripts || yarn install --frozen-lockfile || pnpm install --frozen-lockfile\n",
    "python": "      - uses: actions/setup-python@v5\n        with: { python-version: '3.x' }\n      - run: if [ -f requirements.txt ]; then pip install -r requirements.txt; elif [ -f pyproject.toml ]; then pip install .; fi\n",
    "java": "      - uses: actions/setup-java@v4\n        with: { distribution: temurin, java-version: '21' }\n",
    "go": "      - uses: actions/setup-go@v5\n        with: { go-version: stable }\n",
    "dotnet": "      - uses: actions/setup-dotnet@v4\n        with: { dotnet-version: '8.0.x' }\n      - run: dotnet restore\n",
    "ruby": "      - uses: ruby/setup-ruby@v1\n        with: { bundler-cache: true }\n",
    "php": "      - uses: shivammathur/setup-php@v2\n        with: { php-version: '8.3' }\n",
    "rust": "",
}


REUSABLE = os.environ.get("SNYK_REUSABLE_WORKFLOWS", "brightsheets/reusable-workflows@v1")


def private_go_owners(repo_dir, owners):
    """Owners from `owners` that go.mod requires modules from (github.com/<owner>/...)."""
    try:
        text = open(os.path.join(repo_dir, "go.mod")).read()
    except OSError:
        return []
    found = {m.lower() for m in re.findall(r"github\.com/([A-Za-z0-9_.-]+)/", text.split("\n", 1)[-1])}
    return [o for o in owners if o.lower() in found]


def go_caller(s, a):
    """Caller workflow for reusable go-ci.yaml."""
    repo, ref = REUSABLE.split("@", 1)
    branch = s.get("branch") or "main"
    priv = private_go_owners(a.repo_dir, a.private_owners.split(",")) if a.repo_dir else []
    dockerfiles = [c for c in s.get("containers", []) if "compose" not in c.lower()]
    w = [f"snyk-org: {a.org}", f"snyk-severity-threshold: {a.severity}"]
    if priv:
        w.append(f"go-private-owners: {','.join(priv)}")
    if dockerfiles:
        f = dockerfiles[0]
        w.append("docker-build: true")
        if f != "Dockerfile":
            w.append(f"docker-file: {f}")
            w.append(f"docker-context: {f.rsplit('/', 1)[0] if '/' in f else '.'}")
    sec = ["snyk-token: ${{ secrets.SNYK_TOKEN }}"]
    if priv:
        sec.append("go-modules-token: ${{ secrets.GO_MODULES_TOKEN }}")
    needs = "SNYK_TOKEN" + (" and GO_MODULES_TOKEN (read access to the private modules)" if priv else "")
    out = (f"# Generated by snyk-onboard. Runs {repo}/.github/workflows/go-ci.yaml@{ref}:\n"
           "# lint, tests, Snyk Open Source + Code" + (", Docker build + Snyk Container" if dockerfiles else "") + ".\n"
           f"# Snyk is report-only (Security tab + PR comment). Needs secret {needs}.\n"
           "name: CI\non:\n  push:\n"
           f"    branches: [{branch}, \"hotfix/**\"]\n  pull_request:\n  workflow_dispatch:\n"
           # packages: write always: GitHub checks nested jobs' permissions even when they're skipped.
           "permissions:\n  contents: read\n  actions: read\n  security-events: write\n  pull-requests: write\n"
           "  packages: write\n"
           "jobs:\n  ci:\n"
           f"    uses: {repo}/.github/workflows/go-ci.yaml@{ref}\n"
           "    with:\n" + "".join(f"      {x}\n" for x in w) +
           "    secrets:\n" + "".join(f"      {x}\n" for x in sec))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stack")
    ap.add_argument("--severity", default="high", choices=["low", "medium", "high", "critical"])
    ap.add_argument("--org", default=os.environ.get("SNYK_ORG", "brightsheets"),
                    help="Snyk org slug (default: $SNYK_ORG, else brightsheets)")
    ap.add_argument("--repo-dir", help="checkout of the repo, to read go.mod for private module owners")
    ap.add_argument("--private-owners", default=os.environ.get("GITHUB_OWNER", "brightsheets"),
                    help="comma-separated owners whose Go modules are private (default brightsheets)")
    ap.add_argument("--standalone", action="store_true", help="self-contained workflow even for Go repos")
    a = ap.parse_args()
    s = json.load(open(a.stack))
    if "go" in s.get("ecosystems", {}) and not a.standalone:
        out = go_caller(s, a)
        if "iac" in s["snyk_products"]:  # go-ci doesn't scan IaC; add a job for it
            out += ("  iac:\n    runs-on: ubuntu-latest\n    env:\n      SNYK_TOKEN: ${{ secrets.SNYK_TOKEN }}\n"
                    "    steps:\n      - uses: actions/checkout@v7\n      - uses: snyk/actions/setup@master  # pin to a commit SHA\n"
                    f"      - run: snyk iac test --severity-threshold={a.severity} --org={a.org} --sarif-file-output=snyk-iac.sarif\n"
                    "        continue-on-error: true\n      - if: always()\n        uses: github/codeql-action/upload-sarif@v4\n"
                    "        with: { sarif_file: snyk-iac.sarif, category: snyk-iac }\n        continue-on-error: true\n")
        print(out, end="")
        return
    prod = s["snyk_products"]
    org = f" --org={a.org}" if a.org else ""
    sev = f" --severity-threshold={a.severity}"

    jobs = []
    head = ("    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n"
            "      - uses: snyk/actions/setup@master  # pin to a commit SHA for production\n")
    env = "    env:\n      SNYK_TOKEN: ${{ secrets.SNYK_TOKEN }}\n"

    if "open_source" in prod:
        setup = "".join(SETUP.get(e, "") for e in s["ecosystems"] if e in SETUP)
        if "kotlin" in s["ecosystems"] and "java" not in s["ecosystems"]:
            setup += SETUP["java"]
        jobs.append("  open-source:\n" + env + head + setup +
                    f"      - run: snyk test --all-projects --detection-depth=6{sev}{org} --sarif-file-output=snyk-os.sarif\n"
                    "      - if: always() && github.event_name == 'push' && github.ref_name == github.event.repository.default_branch\n"
                    f"        run: snyk monitor --all-projects --detection-depth=6{org}\n"
                    "      - if: always()\n        uses: github/codeql-action/upload-sarif@v3\n"
                    "        with: { sarif_file: snyk-os.sarif, category: snyk-open-source }\n        continue-on-error: true\n")
    if "code" in prod:
        jobs.append("  code:\n" + env + head +
                    f"      - run: snyk code test{sev}{org} --sarif-file-output=snyk-code.sarif\n"
                    "      - if: always()\n        uses: github/codeql-action/upload-sarif@v3\n"
                    "        with: { sarif_file: snyk-code.sarif, category: snyk-code }\n        continue-on-error: true\n")
    if "iac" in prod:
        jobs.append("  iac:\n" + env + head +
                    f"      - run: snyk iac test{sev}{org} --sarif-file-output=snyk-iac.sarif\n"
                    "      - if: always()\n        uses: github/codeql-action/upload-sarif@v3\n"
                    "        with: { sarif_file: snyk-iac.sarif, category: snyk-iac }\n        continue-on-error: true\n")
    if "unmanaged_cpp" in prod:
        jobs.append("  unmanaged-cpp:\n" + env + head + f"      - run: snyk test --unmanaged{sev}{org}\n")
    if "container" in prod:
        steps = ""
        for i, f in enumerate([c for c in s["containers"] if "compose" not in c.lower()][:5]):
            ctx = f.rsplit("/", 1)[0] if "/" in f else "."
            tag = f"snyk-scan-{i}:${{{{ github.sha }}}}"
            steps += (f"      - run: docker build -t {tag} -f {f} {ctx}\n"
                      f"      - run: snyk container test {tag} --file={f}{sev}{org}\n"
                      "      - if: always() && github.event_name == 'push' && github.ref_name == github.event.repository.default_branch\n"
                      f"        run: snyk container monitor {tag} --file={f}{org}\n")
        if steps:
            jobs.append("  container:\n" + env + head + steps)

    print("# Generated by snyk-onboarding plugin. Requires repo/org secret SNYK_TOKEN.\n"
          "name: Snyk\non:\n  pull_request:\n  push:\n    branches: [main, master]\n  schedule:\n    - cron: '0 6 * * 1'\n"
          "permissions:\n  contents: read\n  security-events: write\n"
          "jobs:\n" + "\n".join(jobs), end="")


if __name__ == "__main__":
    main()
